fn main() {
    let test_cases = vec![
        ((vec![13, -1, 8, 12, 3, 9], 12), 3),
        ((vec![13, -1, 8, 12, 3, 9], 2), 0),
        ((vec![13, -1, 8, 12, 3, 9], 10), 0),
        ((vec![1, 4, -5, 5, 10], 5), 3),
        ((vec![13, -1, 8, 12, 3, 9, 7, 5, 9, 10], 75), 1),
        (([13, -1, 8, 12, 3, 9].repeat(20_000), 12), 60_000),
        (([13, -1, 8, 12, 3, 9, 7, 5, 9, 10].repeat(10_000), 24), 30_000),
        
        // Edge cases
        ((vec![], 5), 0),
        ((vec![5], 5), 1),
        ((vec![1], 5), 0),
        ((vec![0, 0, 0], 0), 6),
        ((vec![-1, -2, -3], -3), 2),
    ];

    std::process::exit(
        run_tests!(&test_cases, |input| count_arrs(&input.0, input.1))
    );
}