fn main() {
    let test_cases = vec![
        ((50, vec![10, 20, 30], vec![60, 100, 120]), (220, vec![0, 1, 1])),
        ((60, vec![10, 20, 30], vec![60, 100, 120]), (280, vec![1, 1, 1])),
        ((9, vec![10, 20, 30], vec![60, 100, 120]), (0, vec![0, 0, 0])),
        ((0, vec![10, 20, 30], vec![60, 100, 120]), (0, vec![0, 0, 0])),
        ((5, vec![], vec![]), (0, vec![])),
        (
            (
                5,
                vec![10, 20, 30].repeat(100),
                vec![60, 100, 120].repeat(100),
            ),
            (0, vec![0; 300]),
        ),
        (
            (
                10,
                vec![10, 20, 30].repeat(10_000),
                vec![60, 100, 120].repeat(10_000),
            ),
            (60, {
                let mut mask = vec![0; 30_000];
                mask[0] = 1;
                mask
            }),
        ),

        // Edge cases
        ((10, vec![10], vec![50]), (50, vec![1])),
        ((9, vec![10], vec![50]), (0, vec![0])),
        ((50, vec![10, 20], vec![100, 200]), (300, vec![1, 1])),
        ((15, vec![10, 10, 10], vec![60, 60, 60]), (60, vec![1, 0, 0])),
        ((10, vec![5, 5, 5], vec![10, 20, 30]), (50, vec![0, 1, 1])),
    ];

    std::process::exit(
        run_tests!(&test_cases, |input| knapsack(input.0, &input.1, &input.2))
    );
}