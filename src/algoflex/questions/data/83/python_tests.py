import sys

test_cases = [
    # Basic cases
    [([2, 4, 3], [5, 6, 4]), [7, 0, 8]],  # 342 + 465 = 807
    [([0], [0]), [0]],  # 0 + 0 = 0
    [([1], [2]), [3]],  # 1 + 2 = 3
    [([5], [5]), [0, 1]],  # 5 + 5 = 10
    [([9], [1]), [0, 1]],  # 9 + 1 = 10
    # Single-digit numbers
    [([1], [1]), [2]],
    [([4], [5]), [9]],
    [([8], [1]), [9]],
    [([9], [9]), [8, 1]],  # 9 + 9 = 18
    # Carry propagation
    [([9, 9], [1]), [0, 0, 1]],  # 99 + 1 = 100
    [([9, 9, 9], [1]), [0, 0, 0, 1]],  # 999 + 1 = 1000
    [([9, 9, 9, 9], [1]), [0, 0, 0, 0, 1]],  # 9999 + 1 = 10000
    [([9, 9, 9, 9, 9], [1]), [0, 0, 0, 0, 0, 1]],
    [([9, 9, 9], [9, 9, 9]), [8, 9, 9, 1]],  # 999 + 999 = 1998
    # Different lengths
    [([1], [9, 9]), [0, 0, 1]],  # 1 + 99 = 100
    [([1], [9, 9, 9]), [0, 0, 0, 1]],  # 1 + 999 = 1000
    [([5], [5, 5]), [0, 6]],  # 5 + 55 = 60
    [([2, 4], [5, 6, 4]), [7, 0, 5]],  # 42 + 465 = 507
    [([2, 4, 3], [5]), [7, 4, 3]],  # 342 + 5 = 347
    [([1, 2, 3], [9, 9]), [0, 2, 4]],  # 321 + 99 = 420
    # One number is zero
    [([0], [1]), [1]],
    [([0], [9]), [9]],
    [([0], [1, 2, 3]), [1, 2, 3]],
    [([1, 2, 3], [0]), [1, 2, 3]],
    # Zeros inside the numbers
    [([0, 1], [0, 1]), [0, 2]],  # 10 + 10 = 20
    [([0, 0, 1], [0, 0, 1]), [0, 0, 2]],  # 100 + 100 = 200
    [([1, 0, 1], [9, 0, 9]), [0, 1, 0, 1]],  # 101 + 909 = 1010
    [([1, 0, 0], [9, 9]), [0, 0, 1]],  # 100 + 99 = 199
    [([0, 0, 1], [9, 9]), [9, 9, 1]],  # 100 + 99 = 199
    # Alternating digits
    [([1, 2, 1], [3, 4, 3]), [4, 6, 4]],  # 121 + 343 = 464
    [([9, 0, 9], [1, 0, 1]), [0, 1, 0, 1]],  # 909 + 101 = 1010
    [([8, 1, 8], [2, 9, 2]), [0, 1, 1, 1]],  # 818 + 292 = 1110
    # Multiple carries but not all 9s
    [([5, 6, 7], [4, 5, 6]), [9, 1, 4, 1]],  # 765 + 654 = 1419
    [([7, 8, 9], [3, 2, 1]), [0, 1, 1, 1]],  # 987 + 123 = 1110
    [([9, 8, 7], [1, 2, 3]), [0, 1, 1, 1]],  # 789 + 321 = 1110
    [([6, 9, 9], [4, 0, 1]), [0, 0, 1, 1]],  # 996 + 104 = 1100
    # Same-length numbers
    [([1, 1], [2, 2]), [3, 3]],
    [([1, 2], [3, 4]), [4, 6]],
    [([4, 3, 2], [1, 2, 3]), [5, 5, 5]],
    [([9, 8, 7], [1, 1, 1]), [0, 0, 9]],  # 789 + 111 = 900
    [([5, 5, 5, 5], [4, 4, 4, 4]), [9, 9, 9, 9]],
    # Larger numbers
    [
        ([3, 4, 5, 6, 7], [7, 6, 5, 4, 3]),
        [0, 1, 1, 1, 1, 1],  # 76543 + 34567 = 111110
    ],
    [
        ([9, 8, 7, 6, 5, 4], [1, 2, 3, 4, 5, 6]),
        [0, 1, 1, 1, 1, 1, 1],
    ],
    # Maximum digit values
    [([9] * 10, [9] * 10), [8] + [9] * 9 + [1]],  # 9999999999 * 2
    # Maximum-length lists: all 1s
    [([1] * 100, [1] * 100), [2] * 100],
    # Maximum-length lists: 9s + 1
    [([9] * 100, [1]), [0] * 100 + [1]],
    # Maximum-length lists: 1 + 999...999
    [([1], [9] * 100), [0] * 100 + [1]],
    # Maximum-length lists: all 9s
    [([9] * 100, [9] * 100), [8] + [9] * 99 + [1]],
    # Maximum-length lists with alternating digits
    [
        ([1, 2] * 50, [3, 4] * 50),
        [4, 6] * 50,
    ],
]


def array_to_list(arr):
    dummy = ListNode()  # type: ignore # noqa: F821
    curr = dummy
    for val in arr:
        curr.next = ListNode(val)  # type: ignore # noqa: F821
        curr = curr.next
    return dummy.next


def list_to_array(head):
    result = []
    curr = head
    while curr:
        result.append(curr.val)
        curr = curr.next
    return result


