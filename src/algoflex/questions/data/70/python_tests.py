import sys

test_cases = [
    # Empty
    [([], 1), [-1, -1]],
    # Single element
    [([1], 1), [0, 0]],
    [([1], 0), [-1, -1]],
    # Two elements
    [([1, 2], 1), [0, 0]],
    [([1, 2], 2), [1, 1]],
    [([1, 2], 3), [-1, -1]],
    # All same
    [([2, 2, 2, 2], 2), [0, 3]],
    [([2, 2, 2, 2], 3), [-1, -1]],
    # Basic examples
    [([5, 7, 7, 8, 8, 10], 8), [3, 4]],
    [([5, 7, 7, 8, 8, 10], 6), [-1, -1]],
    # Target at beginning
    [([1, 1, 2, 3, 4], 1), [0, 1]],
    [([1, 2, 3, 4], 1), [0, 0]],
    # Target at end
    [([1, 2, 3, 4, 4], 4), [3, 4]],
    [([1, 2, 3, 4], 4), [3, 3]],
    # Middle large block
    [([1, 2, 3, 3, 3, 3, 4, 5], 3), [2, 5]],
    # No occurrence between values
    [([1, 3, 5, 7], 4), [-1, -1]],
    # Negative numbers
    [([-5, -4, -4, -4, -3, -1], -4), [1, 3]],
    [([-5, -4, -4, -4, -3, -1], -2), [-1, -1]],
    # Mixed negative and positive
    [([-10, -5, 0, 0, 0, 5, 10], 0), [2, 4]],
    [([-10, -5, 0, 0, 0, 5, 10], -10), [0, 0]],
    # Extreme values
    [([-(10**9), 0, 10**9], -(10**9)), [0, 0]],
    [([-(10**9), 0, 10**9], 10**9), [2, 2]],
    [([-(10**9), 0, 10**9], 1), [-1, -1]],
    # Large duplicate block
    [([1] * 1_000, 1), [0, 999]],
    [([1] * 1_000, 2), [-1, -1]],
    # Increasing sequence
    [(list(range(1_000)), 500), [500, 500]],
    [(list(range(1_000)), 1_001), [-1, -1]],
    # Large middle block
    [
        (
            list(range(500)) + [500] * 1_000 + list(range(501, 1_000)),
            500,
        ),
        [500, 1_499],
    ],
    # Stress near 10^5
    [([1] * 50_000 + [2] * 50_000, 2), [50_000, 99_999]],
    [([1] * 50_000 + [2] * 50_000, 1), [0, 49_999]],
    # Target smaller than all
    [([5, 6, 7, 8], 1), [-1, -1]],
    # Target larger than all
    [([5, 6, 7, 8], 10), [-1, -1]],
    # Small duplicate blocks
    [([1, 1, 2, 2, 3, 3, 4, 4], 3), [4, 5]],
    # Large sparse
    [(list(range(0, 200_000, 2)), 100_000), [50_000, 50_000]],
    [(list(range(0, 200_000, 2)), 99_999), [-1, -1]],
    # Single large block in center
    [([0] * 10_000 + [1] * 80_000 + [2] * 10_000, 1), [10_000, 89_999]],
    # Edge binary-search traps
    [([2, 2, 2, 3, 4, 5], 2), [0, 2]],
    [([1, 2, 3, 4, 4, 4], 4), [3, 5]],
    # Very large values
    [([10**9] * 100_000, 10**9), [0, 99_999]],
    # Additional edge cases
    [([0, 0], 0), [0, 1]],
    [([-1, -1, 0, 0, 1, 1], -1), [0, 1]],
    [([-1, -1, 0, 0, 1, 1], 1), [4, 5]],
]

